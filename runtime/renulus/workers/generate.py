"""Deterministic schema/TS generation from worker_contracts' strict Python models."""
from __future__ import annotations

import json
from pathlib import Path

from renulus.worker_contracts import FRAME, LaunchConfig, PROTOCOL, SUPPORTED_COMMANDS


def schema_document():
    schema = FRAME.json_schema()
    launch = LaunchConfig.model_json_schema()
    schema["$defs"].update(launch.pop("$defs"))
    schema["$defs"]["LaunchConfig"] = launch
    return {"$schema": "https://json-schema.org/draft/2020-12/schema",
            "$id": "urn:renulus:worker:1", **schema}


def ts_type(node):
    if "$ref" in node:
        return node["$ref"].rsplit("/", 1)[-1]
    if "const" in node:
        return json.dumps(node["const"])
    if "enum" in node:
        return " | ".join(json.dumps(value) for value in node["enum"])
    for union in ("anyOf", "oneOf"):
        if union in node:
            return "(" + " | ".join(ts_type(value) for value in node[union]) + ")"
    kind = node.get("type")
    if kind == "object":
        required = node.get("required", [])
        return "{\n" + "".join("  " + json.dumps(key) + ("" if key in required else "?")
            + ": " + ts_type(value) + ";\n" for key, value in node.get("properties", {}).items()) + "}"
    if kind == "array":
        return "Array<" + ts_type(node["items"]) + ">"
    return {"string": "string", "integer": "number", "number": "number",
            "boolean": "boolean", "null": "null"}[kind]


def generated_files():
    schema = schema_document()
    source = "// Generated by python -m renulus.workers.generate; do not edit.\n"
    source += "// Validate untrusted values with worker.schema.json; TS types alone are not validation.\n"
    source += f"export const WORKER_PROTOCOL = {json.dumps(PROTOCOL)} as const;\n"
    source += "export const SUPPORTED_COMMANDS = " + json.dumps(SUPPORTED_COMMANDS) + " as const;\n"
    for name, node in sorted(schema["$defs"].items()):
        source += f"export type {name} = {ts_type(node)};\n\n"
    source += "export type WorkerFrame = " + ts_type(schema) + ";\n"
    names = [name for name in schema["$defs"] if name.endswith("Command")]
    source += "export type WorkerCommand = " + " | ".join(sorted(names)) + ";\n"
    return {"worker.schema.json": json.dumps(schema, indent=2, ensure_ascii=True) + "\n",
            "worker.ts": source}


def main():
    root = Path(__file__).resolve().parents[3] / "packages" / "contracts"
    for name, content in generated_files().items():
        (root / name).write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
